  <p>Catch the brightest fireflies on a summer night. Each round, everyone secretly picks how many dice to roll. Fewer dice roll first, so the right roll with a small hand can beat a big one to the prize.</p>

  <h3>Your kit</h3>
  <ul>
    <li><strong>5 plain dice</strong> (1–6).</li>
    <li><strong>2 lanterns:</strong> a 1–12 die and a 1–20 die. After you use one, it rests for the next round.</li>
    <li><strong>Charms</strong> (hold up to 3). You start with one.
      <ul>
        <li><strong>Nudge:</strong> moves one die 1 up or down. Nudges are used for you, to catch the most points.</li>
        <li><strong>Spare:</strong> adds its number to your roll. It doesn’t count as a die for who rolls first.</li>
        <li><strong>Brag:</strong> +2 points if you catch anything this round.</li>
      </ul>
    </li>
  </ul>

  <h3>Each round</h3>
  <ol>
    <li><strong>Fireflies fly in.</strong> Each shows its points and what a roll needs, like “Total 11+” or “A pair”. Uncaught fireflies stay for later rounds.</li>
    <li><strong>Cast in secret.</strong> Pick your dice, lanterns and any charms before time runs out. You can also sit the round out. While you pick, each firefly shows roughly how often your pick would roll it.</li>
    <li><strong>Roll, fewest dice first.</strong> Players with the same number of dice roll together.</li>
    <li><strong>Catch.</strong> Your roll catches every firefly it meets. If two players rolling together can catch the same one, the lower total gets it. A tie leaves it in the meadow.</li>
    <li><strong>Afterwards.</strong> Charms you cast are used up. Catch nothing and you get a new charm.</li>
  </ol>

  <h3>Flickers ✦</h3>
  <p>Some fireflies do something as they arrive: bring one more firefly, give everyone a charm, or wake every resting lantern.</p>

  <h3>Bigger groups</h3>
  <ul>
    <li>More players means more fireflies each round.</li>
    <li>With 8 or more players, the host can open <strong>two meadows</strong>. You pick one when you cast, and only compete with players in the same meadow.</li>
    <li>Late arrivals can join during the first half of the game.</li>
    <li>With <strong>No limit</strong> on time, there’s no clock at all: each round waits for everyone to cast, and the results stay up until everyone taps Next round. The host can skip ahead if someone’s away.</li>
  </ul>

  <h3>Winning</h3>
  <p>After the last round, the most points wins. A tie goes to whoever caught fewer fireflies.</p>
