  <p>One player knows where a hidden target sits on a dial between two opposites. Can their team find it from a single clue?</p>

  <h3>Each round</h3>
  <ol>
    <li>The <strong>Psychic</strong> sees a card with two ends, such as “Freezing ↔ Scorching”, and a hidden target somewhere on the dial. They can swap to a different card if it’s a tough one.</li>
    <li>The Psychic gives a <strong>clue</strong> that fits the target’s spot between the two ends. For a target near “Scorching”, that could be “a sauna”.</li>
    <li>The Psychic’s teammates talk it over and turn the <strong>shared dial</strong>. Anyone on the team can move it. Once everyone presses <strong>Lock in</strong>, the dial is final, and moving it un-readies everyone.</li>
    <li>In team play, the <strong>other team</strong> then guesses whether the target is to the left or right of the dial.</li>
    <li>The target is revealed and points are scored.</li>
  </ol>

  <h3>Scoring</h3>
  <ul>
    <li><strong>Bullseye</strong> (the middle band): 4 points.</li>
    <li><strong>Next to it:</strong> 3 points.</li>
    <li><strong>Outer bands:</strong> 2 points.</li>
    <li><strong>Left or right:</strong> 1 point to the other team for guessing the right side, unless the dial hit the bullseye.</li>
  </ul>

  <h3>Two ways to play</h3>
  <ul>
    <li><strong>Two teams:</strong> teams take turns, and each team’s Psychic rotates. The first team to the target score wins. If it’s tied, keep playing until one team is ahead.</li>
    <li><strong>One team (co-op):</strong> everyone plays together and takes turns as Psychic, for a set number of rounds. Aim for the highest team score.</li>
  </ul>
