  <p>Four mascots race. Nobody drives them: you bet on how it goes, then sneak a card into the race deck to help your picks or wreck the others. Three races, and the richest bettor wins.</p>

  <h3>The mascots</h3>
  <p>Biscuit the dog, Waddles the duck, Pickles the frog and Bandit the raccoon. Each race card moves one of them, or all of them at once.</p>

  <h3>Each race</h3>
  <ol>
    <li><strong>Take tickets.</strong> Players take turns picking from the ticket piles, snaking back and forth, two tickets each (three each with two players). The poorest player picks first. The best tickets in each pile go first.</li>
    <li><strong>Safe or risky.</strong> A <strong>safe</strong> mascot ticket pays for 1st, 2nd or 3rd. A <strong>risky</strong> one pays more, but only if that mascot wins. The <strong>side bet</strong> piles are Yes and No answers to a question about the race. A wrong risky side bet costs you money, and long shots pay more.</li>
    <li><strong>Stack the deck.</strong> Everyone secretly slips a card from their hand into the race deck.</li>
    <li><strong>Race!</strong> The deck is shuffled, 3 cards are burned unseen, and the rest flip one at a time. The host can pause or change the speed.</li>
    <li><strong>Pay out.</strong> Everyone is dealt a new card and the next race begins. In the last race, you double one of your tickets.</li>
  </ol>

  <h3>The cards</h3>
  <ul>
    <li><strong>Numbers</strong> move a mascot that many spaces. Negative numbers move it back.</li>
    <li><strong>Star</strong> jumps to the next star space, or over the finish line after the last star.</li>
    <li><strong>Fall</strong> knocks a mascot over. Fallen mascots only crawl 1 space at a time.</li>
    <li><strong>Turn around</strong> makes a mascot run the wrong way.</li>
    <li><strong>Swerve</strong> moves a mascot one lane left or right.</li>
    <li><strong>Recover</strong> stands a mascot up and turns it to face the finish.</li>
    <li><strong>All</strong> cards move or recover every mascot at once. They can’t crash, and can’t cross the finish.</li>
  </ul>

  <h3>Chaos</h3>
  <ul>
    <li><strong>Crashes:</strong> running into or through a standing mascot in the same lane knocks it over.</li>
    <li><strong>Out of the race:</strong> falling while already down, getting hit while down, or running off the back or side of the track.</li>
    <li><strong>The fold:</strong> when the deck runs out, the back of the track folds up, and any mascot caught behind the line is out. Then everything is reshuffled.</li>
    <li>Finishers take the best place left. Mascots that go out take the worst. The race ends once three mascots are done.</li>
  </ul>

  <h3>Big groups (9 or more)</h3>
  <p>Everyone picks two bets at once, and you can pick the same one twice. Winners split pots of $18 for 1st, $12 for 2nd, $6 for 3rd, and $18 for the side bet. The deck is shown face up, with three cards swapped between races.</p>
