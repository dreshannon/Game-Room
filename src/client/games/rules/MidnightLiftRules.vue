  <p>One player is the thief, working the market district at night. Everyone else is the Night Watch, sharing five wardens. Over four nights the thief robs five couriers, and after every job has to get back to a secret safehouse. The Watch wins by catching the thief.</p>

  <h3>The map</h3>
  <ul>
    <li>The thief and the couriers move between <strong>doorways</strong> (the round spots).</li>
    <li>Wardens stand on <strong>corners</strong> (the squares) and move along the streets.</li>
    <li>The thief can’t step around a corner with a warden on it.</li>
  </ul>

  <h3>Before the job</h3>
  <ol>
    <li>On the first night, the thief picks a safehouse. Only the thief sees it, and it stays the same all game.</li>
    <li>The thief picks which couriers carry valuables. Some decoys are sent out too, and the Watch sees all of them but can’t tell which are which.</li>
    <li>One Watch player places 7 posts: the five wardens and two decoys. From night 2, five go where the wardens ended last night and two go on empty marked corners.</li>
    <li>The decoy couriers go home. The thief either strikes now or waits. Each wait, the couriers wander one doorway (staying clear of posts) and the thief checks one post. After five rounds, the thief has to strike.</li>
  </ol>

  <h3>The chase</h3>
  <ol>
    <li>The robbery is marked and the posts turn into wardens. The thief starts at the job.</li>
    <li><strong>Thief:</strong> moves one doorway in secret. A <strong>dash</strong> goes two doorways at once and can slip past wardens, but uses two moves. A <strong>rooftop</strong> jumps to any doorway on the same block.</li>
    <li><strong>Watch:</strong> each warden moves up to two corners. They can’t share a corner.</li>
    <li><strong>Watch:</strong> each warden then either <strong>searches</strong> the doorways by its corner, one at a time, until one turns out to be on the thief’s trail tonight (a lantern goes up there), or <strong>arrests</strong> one doorway. An arrest on the thief wins the game.</li>
    <li>Repeat until the thief steps into the safehouse. The last move home has to be a plain step.</li>
  </ol>
  <p>Everyone can see how many moves the thief has used and which were dashes or rooftops, just not where. If the thief runs out of moves before getting home, the Watch wins.</p>

  <h3>Each night</h3>
  <ul>
    <li>Night 1: 8 couriers, 5 carrying. 3 dashes, 2 rooftops.</li>
    <li>Night 2: 7 couriers, 4 carrying. 2 dashes, 2 rooftops.</li>
    <li>Night 3: 6 couriers, 3 carrying. 2 dashes, 1 rooftop. The thief robs two couriers at once, and the Watch doesn’t know which one the thief left from. The Watch moves first.</li>
    <li>Night 4: 4 couriers, 1 carrying. 1 dash, 1 rooftop.</li>
  </ul>
  <p>Couriers never start on a doorway that’s already been robbed. The thief wins by getting home after the fourth night.</p>

  <h3>Lobby options</h3>
  <p>The thief can be picked at random or chosen in the lobby. The host can set 12, 15 or 18 moves a night. People who join partway through join the Watch, and the wardens are shared out again.</p>
